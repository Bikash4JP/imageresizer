import os from 'node:os';
import path from 'node:path';
import { z } from 'zod';

/**
 * All runtime configuration comes from environment variables and is validated
 * once at startup. Invalid configuration fails fast with the offending variable
 * names only — values are never echoed, because some of them are secrets.
 */

const bool = z
  .enum(['true', 'false', '1', '0'])
  .transform((v) => v === 'true' || v === '1');

const int = (min: number, max: number) => z.coerce.number().int().min(min).max(max);

const csv = z
  .string()
  .transform((v) =>
    v
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean),
  );

/**
 * `trust proxy` accepts a hop count or named subnets. `true` (trust everything)
 * is deliberately not accepted: it lets any client spoof X-Forwarded-For and
 * bypass per-IP rate limiting.
 */
const trustProxy = z
  .string()
  .regex(/^(\d{1,2}|false|[a-z0-9.,:/ ]+)$/i, 'must be a hop count, "false", or subnet names')
  .refine((v) => v.trim().toLowerCase() !== 'true', '"true" is unsafe; use a hop count')
  .transform((v): number | string | false => {
    if (v === 'false') return false;
    if (/^\d+$/.test(v)) return Number(v);
    return v;
  });

const origin = z.string().refine((v) => {
  try {
    const u = new URL(v);
    return (u.protocol === 'https:' || u.protocol === 'http:') && u.origin === v;
  } catch {
    return false;
  }
}, 'each entry must be a bare origin such as https://app.example.com');

const envSchema = z.object({
  NODE_ENV: z.enum(['development', 'test', 'production']).default('development'),
  HOST: z.string().default('127.0.0.1'),
  PORT: int(1, 65535).default(8080),
  LOG_LEVEL: z.enum(['fatal', 'error', 'warn', 'info', 'debug', 'trace', 'silent']).default('info'),
  TRUST_PROXY: trustProxy.default('loopback'),

  CORS_ORIGINS: csv.pipe(z.array(origin)).default([]),
  ORIGIN_VERIFY_SECRET: z.string().min(32, 'must be at least 32 characters').optional(),
  /** Also accepted during a rotation window; remove once CloudFront sends the new value. */
  ORIGIN_VERIFY_SECRET_PREVIOUS: z.string().min(32, 'must be at least 32 characters').optional(),
  STATIC_DIR: z.string().optional(),

  MAX_UPLOAD_MB: int(1, 200).default(25),
  MAX_INPUT_PIXELS: int(1_000_000, 268_402_689).default(50_000_000),
  MAX_OUTPUT_DIMENSION: int(64, 16_383).default(10_000),
  MAX_OUTPUT_PIXELS: int(1_000_000, 268_402_689).default(50_000_000),

  PROCESSING_CONCURRENCY: int(1, 64).default(Math.max(1, Math.min(4, Math.floor(os.availableParallelism() / 2)))),
  PROCESSING_QUEUE_LIMIT: int(0, 1000).default(16),
  PROCESSING_TIMEOUT_SECONDS: int(5, 300).default(45),

  RATE_LIMIT_WINDOW_SECONDS: int(1, 3600).default(60),
  RATE_LIMIT_MAX: int(1, 100_000).default(30),

  TEMP_DIR: z.string().default(path.join(os.tmpdir(), 'imageresizer')),
  TEMP_MAX_AGE_SECONDS: int(30, 86_400).default(300),

  /** memory (tests) · file (local dev) · dynamodb (production). Defaults follow NODE_ENV. */
  FEEDBACK_STORE: z.enum(['memory', 'file', 'dynamodb']).optional(),
  FEEDBACK_FILE: z.string().default(path.join('.data', 'feedback.json')),
  FEEDBACK_TABLE: z
    .string()
    .regex(/^[A-Za-z0-9_.-]{3,255}$/, 'must be a DynamoDB table name')
    .optional(),
  /** auto: publish immediately unless the text contains links/contact details · manual: everything waits for approval. */
  FEEDBACK_MODERATION: z.enum(['auto', 'manual']).default('auto'),
  /** Feedback submissions per client IP per hour. */
  FEEDBACK_RATE_LIMIT_MAX: int(1, 1000).default(5),

  /** Generated by `npm run admin:hash-password`; never the password itself. */
  ADMIN_PASSWORD_HASH: z
    .string()
    .regex(/^scrypt:\d+:\d+:\d+:[\w-]+:[\w-]+$/, 'must be generated with `npm run admin:hash-password`')
    .optional(),
  ADMIN_SESSION_SECRET: z.string().min(32, 'must be at least 32 characters').optional(),
  ADMIN_SESSION_HOURS: int(1, 168).default(8),

  PRETTY_LOGS: bool.default(false),
});

export type Env = z.infer<typeof envSchema>;

export interface AppConfig {
  env: Env['NODE_ENV'];
  isProduction: boolean;
  host: string;
  port: number;
  logLevel: Env['LOG_LEVEL'];
  prettyLogs: boolean;
  trustProxy: number | string | false;
  corsOrigins: readonly string[];
  /** Accepted X-Origin-Verify values (current first). Empty disables the check. */
  originVerifySecrets: readonly string[];
  staticDir: string | undefined;
  limits: ProcessingLimits;
  processing: {
    concurrency: number;
    queueLimit: number;
    timeoutSeconds: number;
  };
  rateLimit: { windowMs: number; max: number };
  temp: { dir: string; maxAgeMs: number };
  feedback: FeedbackConfig;
  /** null when the admin area is not configured (its routes then 404). */
  admin: AdminConfig | null;
}

export interface FeedbackConfig {
  store: 'memory' | 'file' | 'dynamodb';
  file: string;
  table: string | undefined;
  moderation: 'auto' | 'manual';
  rateLimitPerHour: number;
}

export interface AdminConfig {
  passwordHash: string;
  sessionSecret: string;
  sessionHours: number;
}

export interface ProcessingLimits {
  maxUploadBytes: number;
  maxInputPixels: number;
  maxOutputDimension: number;
  maxOutputPixels: number;
}

export class ConfigError extends Error {
  constructor(readonly issues: string[]) {
    super(`Invalid environment configuration:\n  - ${issues.join('\n  - ')}`);
    this.name = 'ConfigError';
  }
}

export function loadConfig(source: NodeJS.ProcessEnv = process.env): AppConfig {
  // Treat empty strings as "unset" so `FOO=` in an env file falls back to the default.
  const cleaned = Object.fromEntries(Object.entries(source).filter(([, v]) => v !== undefined && v !== ''));
  const parsed = envSchema.safeParse(cleaned);
  if (!parsed.success) {
    throw new ConfigError(parsed.error.issues.map((i) => `${i.path.join('.') || '(root)'}: ${i.message}`));
  }
  const e = parsed.data;

  if (e.NODE_ENV === 'production' && e.TEMP_DIR === '/') {
    throw new ConfigError(['TEMP_DIR: refusing to use filesystem root']);
  }
  if (e.ORIGIN_VERIFY_SECRET_PREVIOUS && !e.ORIGIN_VERIFY_SECRET) {
    throw new ConfigError(['ORIGIN_VERIFY_SECRET_PREVIOUS: requires ORIGIN_VERIFY_SECRET']);
  }

  const store = e.FEEDBACK_STORE ?? (e.NODE_ENV === 'production' ? 'dynamodb' : e.NODE_ENV === 'test' ? 'memory' : 'file');
  if (store === 'dynamodb') {
    const missing = [];
    if (!e.FEEDBACK_TABLE) missing.push('FEEDBACK_TABLE: required when FEEDBACK_STORE is dynamodb');
    if (!source.AWS_REGION && !source.AWS_DEFAULT_REGION) missing.push('AWS_REGION: required when FEEDBACK_STORE is dynamodb');
    if (missing.length) throw new ConfigError(missing);
  }
  if (!!e.ADMIN_PASSWORD_HASH !== !!e.ADMIN_SESSION_SECRET) {
    throw new ConfigError(['ADMIN_PASSWORD_HASH / ADMIN_SESSION_SECRET: set both to enable the admin area, or neither']);
  }

  return Object.freeze({
    env: e.NODE_ENV,
    isProduction: e.NODE_ENV === 'production',
    host: e.HOST,
    port: e.PORT,
    logLevel: e.LOG_LEVEL,
    prettyLogs: e.PRETTY_LOGS,
    trustProxy: e.TRUST_PROXY,
    corsOrigins: Object.freeze([...e.CORS_ORIGINS]),
    originVerifySecrets: Object.freeze([e.ORIGIN_VERIFY_SECRET, e.ORIGIN_VERIFY_SECRET_PREVIOUS].filter((s): s is string => !!s)),
    staticDir: e.STATIC_DIR ? path.resolve(e.STATIC_DIR) : undefined,
    limits: Object.freeze({
      maxUploadBytes: e.MAX_UPLOAD_MB * 1024 * 1024,
      maxInputPixels: e.MAX_INPUT_PIXELS,
      maxOutputDimension: e.MAX_OUTPUT_DIMENSION,
      maxOutputPixels: e.MAX_OUTPUT_PIXELS,
    }),
    processing: Object.freeze({
      concurrency: e.PROCESSING_CONCURRENCY,
      queueLimit: e.PROCESSING_QUEUE_LIMIT,
      timeoutSeconds: e.PROCESSING_TIMEOUT_SECONDS,
    }),
    rateLimit: Object.freeze({ windowMs: e.RATE_LIMIT_WINDOW_SECONDS * 1000, max: e.RATE_LIMIT_MAX }),
    temp: Object.freeze({ dir: path.resolve(e.TEMP_DIR), maxAgeMs: e.TEMP_MAX_AGE_SECONDS * 1000 }),
    feedback: Object.freeze({
      store,
      file: path.resolve(e.FEEDBACK_FILE),
      table: e.FEEDBACK_TABLE,
      moderation: e.FEEDBACK_MODERATION,
      rateLimitPerHour: e.FEEDBACK_RATE_LIMIT_MAX,
    }),
    admin:
      e.ADMIN_PASSWORD_HASH && e.ADMIN_SESSION_SECRET
        ? Object.freeze({ passwordHash: e.ADMIN_PASSWORD_HASH, sessionSecret: e.ADMIN_SESSION_SECRET, sessionHours: e.ADMIN_SESSION_HOURS })
        : null,
  });
}
